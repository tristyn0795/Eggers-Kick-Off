/*
 * Bundles the game for the iOS/Android app shells (Capacitor).
 *   npm run build:app                      -> app-dist/ talking to the live server
 *   EK_API_BASE=https://... npm run build:app  (point it somewhere else)
 * Then: npx cap sync   (see store/ios/README.md)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'app-dist');
const version = require('../package.json').version;
const apiBase = (process.env.EK_API_BASE || 'https://eggers-kick-off-production.up.railway.app').replace(/\/$/, '');

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, 'public'), out, { recursive: true });
fs.cpSync(path.join(root, 'shared'), path.join(out, 'shared'), { recursive: true });

// The website's service worker isn't used inside the app (the files are already on the device).
fs.rmSync(path.join(out, 'sw.js'), { force: true });

const indexFile = path.join(out, 'index.html');
fs.writeFileSync(indexFile, fs.readFileSync(indexFile, 'utf8').replace(/__ASSET_VERSION__/g, `${version}-app`));
fs.writeFileSync(path.join(out, 'app-config.js'),
  `/* Generated by scripts/build-app.js */\nwindow.EK_API_BASE = ${JSON.stringify(apiBase)};\nwindow.EK_APP_VERSION = ${JSON.stringify(version)};\n`);

console.log(`app-dist/ built (v${version}) -> server ${apiBase}`);
